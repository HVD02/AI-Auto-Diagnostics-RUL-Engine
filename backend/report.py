import os
import time
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import mm
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                 TableStyle, HRFlowable)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

HERE = os.path.dirname(__file__)
REPORT_DIR = os.path.join(HERE, "..", "reports_generated")
os.makedirs(REPORT_DIR, exist_ok=True)

styles = getSampleStyleSheet()
title_style = ParagraphStyle("TitleX", parent=styles["Title"], textColor=colors.HexColor("#0e7490"))
h2 = ParagraphStyle("H2X", parent=styles["Heading2"], textColor=colors.HexColor("#111827"))
body = styles["BodyText"]


def generate_report(vehicle_id, analysis: dict, model_version="v1.0"):
    fname = f"diagnostic_report_{vehicle_id}_{int(time.time())}.pdf"
    fpath = os.path.join(REPORT_DIR, fname)
    doc = SimpleDocTemplate(fpath, pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm)
    story = []

    story.append(Paragraph("AI Auto-Diagnostics & RUL Engine", title_style))
    story.append(Paragraph("Vehicle Diagnostic Report", h2))
    story.append(Spacer(1, 4))
    story.append(Paragraph(f"Vehicle: <b>{vehicle_id}</b>", body))
    story.append(Paragraph(f"Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}", body))
    story.append(Paragraph(f"Model version: {model_version}", body))
    story.append(HRFlowable(width="100%", color=colors.grey))
    story.append(Spacer(1, 8))

    hs = analysis.get("health", {})
    story.append(Paragraph("Vehicle Health", h2))
    story.append(Paragraph(f"Health Score: <b>{hs.get('health_score')}</b> ({hs.get('band')})", body))
    story.append(Spacer(1, 6))

    an = analysis.get("anomaly", {})
    story.append(Paragraph("Anomaly Analysis", h2))
    story.append(Paragraph(f"Status: <b>{an.get('status')}</b> &nbsp; Anomaly ratio: {an.get('anomaly_ratio')}", body))
    if an.get("top_contributors"):
        rows = [["Sensor", "Z-score"]] + [[c["sensor"], str(c["z_score"])] for c in an["top_contributors"]]
        t = Table(rows, hAlign="LEFT")
        t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e5e7eb")),
                                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey)]))
        story.append(t)
    story.append(Spacer(1, 6))

    sf = analysis.get("sensor_fault", {})
    story.append(Paragraph("Sensor Fault Analysis", h2))
    story.append(Paragraph(f"Verdict: <b>{sf.get('verdict')}</b> (confidence {sf.get('confidence')})", body))
    story.append(Spacer(1, 6))

    diag = analysis.get("diagnosis")
    if diag:
        story.append(Paragraph("Fault Diagnosis", h2))
        story.append(Paragraph(f"Primary diagnosis: <b>{diag.get('predicted_label')}</b> "
                                f"(confidence {diag.get('confidence')}, severity {diag.get('severity')})", body))
        if diag.get("shap_explanation"):
            rows = [["Feature", "SHAP contribution"]] + [[e["feature"], str(e["shap_value"])] for e in diag["shap_explanation"]]
            t = Table(rows, hAlign="LEFT")
            t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e5e7eb")),
                                    ("GRID", (0, 0), (-1, -1), 0.5, colors.grey)]))
            story.append(t)
        story.append(Spacer(1, 6))

    rul = analysis.get("rul")
    if rul and rul.get("available"):
        story.append(Paragraph("RUL & Prognostics", h2))
        story.append(Paragraph(f"Predicted RUL: <b>{rul.get('predicted_rul_cycles')} cycles</b> "
                                f"(stage: {rul.get('degradation_stage')})", body))
        story.append(Paragraph(rul.get("disclaimer", ""), styles["Italic"]))
        story.append(Spacer(1, 6))

    maint = analysis.get("maintenance")
    if maint:
        story.append(Paragraph("Maintenance Recommendation", h2))
        for m in maint:
            story.append(Paragraph(f"<b>{m.get('category')} — {m.get('subcategory')}</b>", body))
            if m.get("symptoms"):
                story.append(Paragraph("Symptoms: " + ", ".join(m["symptoms"]), body))
        story.append(Spacer(1, 6))

    story.append(HRFlowable(width="100%", color=colors.grey))
    story.append(Spacer(1, 6))
    story.append(Paragraph(
        "Disclaimer: This report is generated by an automated diagnostic system for demonstration "
        "and educational purposes. It does not replace inspection by a certified technician. "
        "RUL figures (where shown) are validated on NASA turbofan engine data, not passenger-vehicle "
        "run-to-failure data.", styles["Italic"]))

    doc.build(story)
    return fpath
